type ValidationMessages = Record<keyof typeof studentsMessages.en.validation, string>;

/**
 * A form error with its message in the viewer's language.
 *
 * The schema in `lib/validation/students.ts` writes English messages. They are
 * matched against the English half of `validation` above and swapped for the
 * viewer's; zod's own "too long" message is matched by issue type. Anything else
 * — notably a field error the API sent back — is shown exactly as received.
 */
export function localizeFieldError(
  error: { message?: string; type?: string } | undefined,
  messages: ValidationMessages,
): { message?: string } | undefined {
  if (!error?.message) return error;
  if (error.type === "too_big") return { message: messages.tooLong };
  const english = studentsMessages.en.validation;
  const key = (Object.keys(english) as (keyof ValidationMessages)[]).find(
    (candidate) => english[candidate] === error.message,
  );
  return key ? { message: messages[key] } : error;
}

